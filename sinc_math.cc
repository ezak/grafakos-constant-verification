// -------------------------------------------------------------------------
// ex1_hilb_yam.m
// -------------------------------------------------------------------------
void
ex1_hilb_yam ()
{
  std::cout << "\n--- Running ex1_hilb_yam ---" << std::endl;
  int    M = 20;
  int    N = 20;
  double h = PI / std::sqrt (N);
  int    m = M + N + 1;

  Eigen::VectorXd z = Sincpoints2 (0.0, 1.0, M, N, h);

  Eigen::VectorXd f (m);
  Eigen::VectorXd ge (m);

  double TT = std::exp (-M * h);
  double Q  = std::exp (h);

  for (int j = 1; j <= m; ++j)
    {
      int k      = j - M - 1;
      f (j - 1)  = TT / std::pow (1.0 + TT, 2);
      TT         = Q * TT;
      ge (j - 1) = (1.0 / PI) * (0.5 - z (j - 1) - f (j - 1) * k * h);
    }

  Eigen::MatrixXcd C  = Hilb_yam2 (0.0, 1.0, M, N, h);
  Eigen::VectorXcd ff = f.cast<std::complex<double>> ();

  // gg = -imag(C * ff)
  Eigen::VectorXd gg = -(C * ff).imag ();

  // Emulating plotting/saving
  export_to_csv ("Exact_and_Yamamoto_Approx.csv", z, gg);

  Eigen::VectorXd diff = ge - gg;
  export_to_csv ("Exact_minus_Yamamoto_Approx.csv", z, diff);
}

