// -------------------------------------------------------------------------
// 'Sincpoints2.m'
// -------------------------------------------------------------------------
Eigen::VectorXd
Sincpoints2 (double a, double b, int M, int N, double h)
{
  int             m = M + N + 1;
  Eigen::VectorXd z (m);
  double          T  = std::exp (h);
  double          TT = 1.0 / std::pow (T, M);
  for (int j = 0; j < m; ++j)
    {
      z (j) = (a + b * TT) / (1.0 + TT);
      TT    = T * TT;
    }
  return z;
}

// -------------------------------------------------------------------------
// 'weights2.m'
// -------------------------------------------------------------------------
Eigen::VectorXd
weights2 (double a, double b, int M, int N, double h)
{
  int             m = M + N + 1;
  Eigen::VectorXd w (m);
  double          bmah = (b - a) * h;
  double          T    = std::exp (h);
  double          TT   = 1.0 / std::pow (T, M);
  for (int j = 0; j < m; ++j)
    {
      w (j) = bmah * TT / std::pow (1.0 + TT, 2);
      TT    = T * TT;
    }
  return w;
}

// -------------------------------------------------------------------------
// 'Int2_m.m'
// -------------------------------------------------------------------------
Eigen::MatrixXd
Int2_m (double a, double b, int M, int N, double h)
{
  int             m = M + N + 1;
  Eigen::MatrixXd B = Im (m).transpose ();
  Eigen::VectorXd w = weights2 (a, b, M, N, h);
  return B * w.asDiagonal ();
}

// -------------------------------------------------------------------------
// 'Int2_p.m'
// -------------------------------------------------------------------------
Eigen::MatrixXd
Int2_p (double a, double b, int M, int N, double h)
{
  int             m = M + N + 1;
  Eigen::MatrixXd B = Im (m);
  Eigen::VectorXd w = weights2 (a, b, M, N, h);
  return B * w.asDiagonal ();
}

// -------------------------------------------------------------------------
// 'Hilb_yam.m'
// -------------------------------------------------------------------------
Eigen::MatrixXcd
Hilb_yam (const Eigen::MatrixXd &A, const Eigen::MatrixXd &B)
{
  Eigen::EigenSolver<Eigen::MatrixXd> esA (A);
  Eigen::EigenSolver<Eigen::MatrixXd> esB (B);

  Eigen::MatrixXcd X  = esA.eigenvectors ();
  Eigen::VectorXcd sA = esA.eigenvalues ();

  Eigen::MatrixXcd Y  = esB.eigenvectors ();
  Eigen::VectorXcd sB = esB.eigenvalues ();

  Eigen::VectorXcd tA (A.rows ());
  Eigen::VectorXcd tB (B.rows ());

  for (int j = 0; j < A.rows (); ++j)
    tA (j) = std::log (sA (j));
  for (int j = 0; j < B.rows (); ++j)
    tB (j) = std::log (sB (j));

  Eigen::MatrixXcd T_A = tA.asDiagonal ();
  Eigen::MatrixXcd T_B = tB.asDiagonal ();

  Eigen::MatrixXcd E = X * T_A * X.inverse ();
  Eigen::MatrixXcd F = Y * T_B * Y.inverse ();

  std::complex<double> i_pi = I * PI;
  return (F - E) / i_pi;
}

// -------------------------------------------------------------------------
// 'Hilb_yam1.m'
// -------------------------------------------------------------------------
Eigen::MatrixXcd
Hilb_yam1 (int M, int N, double h)
{
  Eigen::MatrixXd A = Int1_p (M, N, h); // Stubs created above
  Eigen::MatrixXd B = Int1_m (M, N, h);
  return Hilb_yam (A, B);
}

