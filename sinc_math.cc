// 'Hilb_yam2.m'
// -------------------------------------------------------------------------
Eigen::MatrixXcd
Hilb_yam2 (double a, double b, int M, int N, double h)
{
  Eigen::MatrixXd A = Int2_p (a, b, M, N, h);
  Eigen::MatrixXd B = Int2_m (a, b, M, N, h);
  return Hilb_yam (A, B);
}

