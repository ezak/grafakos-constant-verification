// ex_1_77_hilb.m
// -------------------------------------------------------------------------
void
ex_1_77_hilb ()
{
  std::cout << "\n--- Running ex_1_77_hilb ---" << std::endl;
  int    M = 25;
  int    N = 25;
  int    m = M + N + 1;
  double h = 1.0 * std::sqrt (1.0 / N);

  Eigen::VectorXd z = Sincpoints2 (-1.0, 1.0, M, N, h);

  Eigen::VectorXd f1 (m), f2 (m), f3 (m), f4 (m);
  for (int j = 0; j < m; ++j)
    {
      double t = z (j);
      f1 (j)   = 1.0 / std::sqrt (1.0 - t * t);
      f2 (j)   = t / std::sqrt (1.0 - t * t);
      f3 (j)   = std::sqrt (1.0 - t * t);
      f4 (j)   = std::pow (t, 3);
    }

  Eigen::MatrixXd  A = Int2_p (-1.0, 1.0, M, N, h);
  Eigen::MatrixXd  B = Int2_m (-1.0, 1.0, M, N, h);
  Eigen::MatrixXcd H = Hilb_yam (A, B);

  Eigen::VectorXcd F1 = H * f1.cast<std::complex<double>> ();
  Eigen::VectorXcd F2 = H * f2.cast<std::complex<double>> ();
  Eigen::VectorXcd F3 = H * f3.cast<std::complex<double>> ();
  Eigen::VectorXcd F4 = H * f4.cast<std::complex<double>> ();

  int              mm = (M + N + 1) - 14;
  Eigen::VectorXd  y (mm);
  Eigen::VectorXcd FF1 (mm), FF2 (mm), FF3 (mm), FF4 (mm);

  for (int j = 0; j < mm; ++j)
    {
      y (j)   = z (j + 7);
      FF1 (j) = F1 (j + 7);
      FF2 (j) = F2 (j + 7);
      FF3 (j) = F3 (j + 7);
      FF4 (j) = F4 (j + 7);
    }

  export_to_csv ("ex1_77_F1.csv", z, F1.real ());
  export_to_csv ("ex1_77_F2.csv", z, F2.real ());
  export_to_csv ("ex1_77_F3.csv", z, F3.real ());
  export_to_csv ("ex1_77_F4.csv", z, F4.real ());
}

// -------------------------------------------------------------------------
// mapped_sinc_fun.m
// -------------------------------------------------------------------------
void
mapped_sinc_fun ()
{
  std::cout << "\n--- Running mapped_sinc_fun ---" << std::endl;
  double h    = 0.9998 / 9998.0;
  int    size = 9998;

  Eigen::VectorXd x (size);
  Eigen::VectorXd y (size);

  for (int i = 1; i <= size; ++i)
    {
      double t  = (i - 0.5) * h;
      double s  = PI * (std::log (t / (1.0 - t)) - 1.0);
      x (i - 1) = t;

      if (std::abs (s) > EPSILON)
        {
          y (i - 1) = std::sin (s) / s;
        }
      else
        {
          y (i - 1) = 1.0;
        }
    }

  export_to_csv ("mapped_sinc.csv", x, y);
}

// -------------------------------------------------------------------------
// verify_grafakos_constant
// -------------------------------------------------------------------------
void
verify_grafakos_constant (double p)
{
  std::cout << "\n--- Running verify_grafakos_constant for p = " << p << " ---" << std::endl;

  // Configure dimensions and interval
  int    M = 40;
  int    N = 40;
  double h = PI / std::sqrt (N);
  int    m = M + N + 1;

  // Generate the discrete Hilbert transform operator on the interval [-1, 1]
  Eigen::MatrixXcd C = Hilb_yam2 (-1.0, 1.0, M, N, h);

  // Sinc quadrature weights for the interval [-1, 1] for integration
  Eigen::VectorXd w = weights2 (-1.0, 1.0, M, N, h);

  double max_ratio  = 0.0;
  int    num_trials = 10000;

  // Monte Carlo simulation to estimate the induced Lp operator norm of C
  for (int i = 0; i < num_trials; ++i)
    {
      // Generate a random complex vector using Eigen's built-in generator
      Eigen::VectorXcd f = Eigen::VectorXcd::Random (m);

      // Apply the discrete Hilbert transform
      Eigen::VectorXcd Cf = C * f;

      double norm_f  = 0.0;
      double norm_Cf = 0.0;

      // Calculate Lp norm sum approximation using sinc integration weights
      for (int j = 0; j < m; ++j)
        {
          norm_f += w (j) * std::pow (std::abs (f (j)), p);
          norm_Cf += w (j) * std::pow (std::abs (Cf (j)), p);
        }

      norm_f  = std::pow (norm_f, 1.0 / p);
      norm_Cf = std::pow (norm_Cf, 1.0 / p);

      if (norm_f > 1e-12)
        {
          double ratio = norm_Cf / norm_f;
          if (ratio > max_ratio)
            {
              max_ratio = ratio;
            }
        }
    }

  // The Grafakos (Pichorides) exact Lp norm for the Hilbert transform
  double theoretical_constant = 0.0;
  if (p >= 2.0)
    {
      theoretical_constant = 1.0 / std::tan (PI / (2.0 * p)); // cot(pi/2p)
    }
  else if (p > 1.0)
    {
      theoretical_constant = std::tan (PI / (2.0 * p)); // tan(pi/2p)
    }

  std::cout << "Monte Carlo Estimated L^" << p << " Operator Norm : " << max_ratio << std::endl;
  std::cout << "Theoretical Grafakos Constant   : " << theoretical_constant << std::endl;

  // We check if the empirically found maximum ratio is correctly bounded
  // by the theoretical constant (adding a tiny margin for float precision)
  if (max_ratio <= theoretical_constant + 1e-7)
    {
      std::cout << "Verification PASSED: Estimated norm is bounded by the Grafakos constant." << std::endl;
    }
  else
    {
      std::cout << "Verification FAILED: Estimated norm exceeds the Grafakos constant." << std::endl;
    }
}

